import { eulReul } from './josa'

test.each([
  ['받침 있음', '11월 그림일기장', '을'],
  ['받침 없음', '11월 그림일기', '를'],
  ['ㄹ받침', '한글', '을'],
  ['숫자(받침 있음)', '모임 3', '을'],
  ['숫자(받침 없음)', '레이어 2', '를'],
  ['0으로 끝남', '2030', '을'],
  ['영문(받침 소리)', 'Team Plan', '을'],
  ['영문(받침 없는 소리)', 'Diary', '를'],
  ['괄호·공백·기호는 건너뜀', '회의(1) ', '을'],
  ['풀어 쓴 한글(NFD)', '한글'.normalize('NFD'), '을'],
  ['읽을 글자가 없음', '🌙', '를'],
])('%s: %s → %s', (_, word, josa) => {
  expect(eulReul(word)).toBe(josa)
})
